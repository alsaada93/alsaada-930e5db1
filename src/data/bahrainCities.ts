/** مركز افتراضي (المنامة) عند عدم توفر إحداثيات المدينة. */
export const BAHRAIN_CENTER = { lat: 26.2235, lng: 50.5876 };

/** يرجّع إحداثيات مركز المدينة إن وُجدت. */
export function cityCenter(city?: string | null): { lat: number; lng: number } | null {
  if (!city) return null;
  return bahrainCityCoords[city.trim()] ?? null;
}

/** يبني رابط خريطة OpenStreetMap مضمّنة مع علامة عند الإحداثيات المعطاة. */
export function osmEmbed(lat: number, lng: number, span = 0.01): string {
  return `https://www.openstreetmap.org/export/embed.html?bbox=${lng - span}%2C${lat - span}%2C${lng + span}%2C${lat + span}&layer=mapnik&marker=${lat}%2C${lng}`;
}
